/// Draws a `TeamSprite` as crisp, unsmoothed pixels.
struct PixelSpriteView: View {
    let sprite: TeamSprite
    /// Main color of the art (the crest's contrast-safe emblem color).
    let ink: Color
    /// The color behind the sprite, painted into `E` pixels as a cut-out.
    let cut: Color

    @Environment(\.displayScale) private var displayScale

    var body: some View {
        Canvas { ctx, size in
            let n = sprite.resolution
            let step = size.width / CGFloat(n)
            // Snap cell edges to whole *device* pixels, not points. A crest is
            // often ~20pt wide, so at 24 cells a point-aligned grid rounds
            // several cells to zero width and visibly mangles the art; at 3x
            // there are still ~2.5 device pixels per cell to land on.
            let scale = max(1, displayScale)
            func snap(_ v: CGFloat) -> CGFloat { (v * scale).rounded() / scale }
            let unit = 1 / scale
            for (r, row) in sprite.rows.enumerated() {
                for (c, ch) in row.enumerated() where ch != "." {
                    let x0 = snap(CGFloat(c) * step)
                    let y0 = snap(CGFloat(r) * step)
                    let x1 = snap(CGFloat(c + 1) * step)
                    let y1 = snap(CGFloat(r + 1) * step)
                    let cell = Path(CGRect(x: x0, y: y0,
                                           width: max(unit, x1 - x0),
                                           height: max(unit, y1 - y0)))
                    switch ch {
                    case "X":
                        ctx.fill(cell, with: .color(ink))
                    case "L":
                        ctx.fill(cell, with: .color(ink))
                        ctx.fill(cell, with: .color(.white.opacity(0.45)))
                    case "D":
                        ctx.fill(cell, with: .color(ink))
                        ctx.fill(cell, with: .color(.black.opacity(0.40)))
                    case "E":
                        ctx.fill(cell, with: .color(cut))
                    default:
                        break
                    }
                }
            }
        }
        .allowsHitTesting(false)
    }
}

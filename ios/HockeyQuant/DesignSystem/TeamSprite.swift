/// Hand-authored pixel-art emblems for team crests.
///
/// Same IP footing as `TeamGlyph`: every sprite depicts the ordinary thing the
/// team is *named* after — a flame, a shark tooth, a maple leaf — drawn from
/// scratch here, never traced from or fitted to a club's actual emblem. Where a
/// faithful depiction would have to be the club's own artwork, the sprite shows
/// the city instead: Chicago is its skyline, never the head on the sweater.
/// Being authored as code there's also no generated-art provenance question and
/// nothing to license or attribute.
///
/// A sprite is a 24x24 grid of characters, one per pixel, and every color comes
/// from `TeamInfo` — so the art themes itself per team and follows a palette
/// retune for free.
///
///   `.` transparent   `X` body      `L` body, lightened
///   `D` body, darkened                `E` cut out to the disc color
///
/// `E` is what makes eyes and visor slits read: it paints the crest's own
/// background back over the art, so the shape looks punched through.
///
/// Authored with `Tools/render_sprites.py`, which draws these grids at three
/// scales. Judge a change there, not in the simulator — screenshots are
/// downscaled well past what 24x24 art can be assessed at, and shapes that
/// look fine blown up routinely turn to mush at crest size.
